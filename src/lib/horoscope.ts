function getDayOfYear(date: Date): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  return Math.floor(diff / (1000 * 60 * 60 * 24)); // 1–366
}

export function getDailyHoroscopeText(date: Date = new Date()): string {
  const day = getDayOfYear(date); // 1–366
  return GEMINI_TEXTS[(day - 1) % GEMINI_TEXTS.length];
}

export function getEnergyLevel(date: Date = new Date()): number {
  // 0.0 – 1.0, varies by day of year for smoother curve across the year
  const day = getDayOfYear(date);
  const seed = day * 7 + date.getFullYear() * 3;
  return 0.35 + ((seed * 1664525 + 1013904223) & 0x7fffffff) % 65 / 100;
}
